const GENERATED_HEADER: &str = "// Auto-generated rust bindings. Do not edit it manually.\n";
const TAURI_SPECTA_HEADER: &str = "// This file has been generated by Tauri Specta. Do not edit this file manually.";

#[derive(Debug, Clone)]
struct CommandTypescript(Typescript);

impl LanguageExt for CommandTypescript {
  type Error = specta_typescript::Error;

  fn export(self, config: &BuilderConfiguration, path: &Path) -> Result<(), Self::Error> {
    LanguageExt::export(self.0, config, path)?;
    normalize_generated_bindings(path)?;

    Ok(())
  }
}

fn normalize_generated_bindings(path: &Path) -> io::Result<()> {
  let bindings = fs::read_to_string(path)?;
  let bindings = bindings
    .replacen(TAURI_SPECTA_HEADER, "", 1)
    .replace("/**  ", "/** ")
    .replace(" *  ", " * ");

  fs::write(path, bindings)
}

#[derive(Debug, Clone)]
struct TypeScriptFormat {
  remapper: Remapper,
}

impl Default for TypeScriptFormat {
  fn default() -> Self {
    let number = <specta_typescript::Number as Type>::definition(&mut Types::default());
    let remapper = Remapper::new()
      .rule(DataType::Primitive(Primitive::usize), number.clone())
      .rule(DataType::Primitive(Primitive::isize), number.clone())
      .rule(DataType::Primitive(Primitive::u64), number.clone())
      .rule(DataType::Primitive(Primitive::i64), number.clone())
      .rule(DataType::Primitive(Primitive::u128), number.clone())
      .rule(DataType::Primitive(Primitive::i128), number.clone())
      .rule(
        <specta_typescript::BigInt as Type>::definition(&mut Types::default()),
        number,
      );

    Self { remapper }
  }
}

impl Format for TypeScriptFormat {
  fn map_types(&self, types: &Types) -> Result<Cow<'_, Types>, specta::FormatError> {
    let types = specta_serde::Format.map_types(types)?;

    Ok(Cow::Owned(self.remapper.remap_types(types.into_owned())))
  }

  fn map_type(&'_ self, types: &Types, data_type: &DataType) -> Result<Cow<'_, DataType>, specta::FormatError> {
    let data_type = specta_serde::Format.map_type(types, data_type)?;

    Ok(Cow::Owned(self.remapper.remap_dt(data_type.into_owned())))
  }
}

fn exporter() -> Typescript {
  let exporter: Exporter = Typescript::default().into();

  exporter.header(GENERATED_HEADER).framework_prelude("").into()
}

fn command_exporter() -> CommandTypescript {
  CommandTypescript(exporter())
}

fn export_types(path: &Path, types: &Types) {
  exporter()
    .export_to(path, types, TypeScriptFormat::default())
    .unwrap_or_else(|error| panic!("Failed to export {}: {error}", path.display()));

  normalize_generated_bindings(path).unwrap_or_else(|error| panic!("Failed to normalize {}: {error}", path.display()));
}

/// Generated type names inside a declared argument type, which are the only ones worth importing.
///
/// An argument type is written as TypeScript rather than as a name, so it may be a primitive, a union, or an array. Only
/// the PascalCase identifiers in it come from the generated module; `string`, `number` and `null` are the language's own
/// and importing them produces a file that does not parse.
fn imported_types(argument_type: &str) -> impl Iterator<Item = &str> {
  argument_type
    .split(|character: char| !character.is_ascii_alphanumeric() && character != '_')
    .filter(|token| token.starts_with(|character: char| character.is_ascii_uppercase()))
}

/// Write the wrappers for one domain's raw commands.
///
/// Specta cannot collect a command returning `tauri::ipc::Response`, so these are generated from the registry instead of
/// written by hand. The registry carries each argument's TypeScript type for exactly this reason; the return is always
/// `ArrayBuffer`, which is what the raw response arrives as.
fn export_raw_commands(path: &Path, plugin_name: &str, commands: &[(&str, &[(&str, &str)])], types_module: &str) {
  if commands.is_empty() {
    return;
  }

  let referenced: BTreeSet<&str> = commands
    .iter()
    .flat_map(|(_, arguments)| {
      arguments
        .iter()
        .flat_map(|(_, argument_type)| imported_types(argument_type))
    })
    .collect();

  let mut contents: String = String::from(GENERATED_HEADER);

  contents.push_str("\nimport { invokeRaw } from \"@/core/ipc/raw\";\n");

  if !referenced.is_empty() {
    contents.push_str(&format!(
      "\nimport {{ {} }} from \"@/core/bindings/{types_module}\";\n",
      referenced.iter().copied().collect::<Vec<&str>>().join(", ")
    ));
  }

  contents
    .push_str("\n/** Commands answering with raw bytes, which Specta cannot type. */\nexport const commands = {\n");

  for (wire_name, arguments) in commands {
    let parameters: String = arguments
      .iter()
      .map(|(name, argument_type)| format!("{name}: {argument_type}"))
      .collect::<Vec<String>>()
      .join(", ");
    let payload: String = arguments
      .iter()
      .map(|(name, _)| (*name).to_string())
      .collect::<Vec<String>>()
      .join(", ");

    contents.push_str(&format!(
      "  {}: ({parameters}): Promise<ArrayBuffer> =>\n    invokeRaw(\"plugin:{plugin_name}|{wire_name}\", {{ {payload} }}),\n",
      to_camel_case(wire_name)
    ));
  }

  contents.push_str("};\n");

  fs::write(path, contents).unwrap_or_else(|error| panic!("Failed to export {}: {error}", path.display()));
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn export_typescript_bindings() {
    let output = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../xrf-ui/src/core/bindings");

    export_types(&output.join("xrf-archive.ts"), &xrf_archive::typescript_bindings());
    export_types(&output.join("xrf-vfs.ts"), &xrf_vfs::typescript_bindings());
    export_types(&output.join("xrf-db.ts"), &xrf_db::typescript_bindings());
    export_types(&output.join("xrf-error.ts"), &xrf_error::typescript_bindings());
    export_types(&output.join("xrf-export.ts"), &xrf_export::typescript_bindings());
    export_types(&output.join("xrf-ltx.ts"), &xrf_ltx::typescript_bindings());
    export_types(&output.join("xrf-visual.ts"), &xrf_visual::typescript_bindings());
    export_types(
      &output.join("xrf-app.ts"),
      &Types::default()
        .register::<ArchiveAudioParameters>()
        .register::<ArchiveAudioPreview>()
        .register::<ArchiveImagePreview>(),
    );

    export_commands::<tauri::Wry>(&output);
  }

  fn export_commands<R: tauri::Runtime>(output: &Path) {
    ArchivesPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-archives.ts"))
      .expect("Failed to export archives commands");
    ConfigsPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-configs.ts"))
      .expect("Failed to export configs commands");
    ExportsPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-exports.ts"))
      .expect("Failed to export exports commands");
    EquipmentIconsPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-equipment-icons.ts"))
      .expect("Failed to export equipment icons commands");
    SpawnPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-spawn.ts"))
      .expect("Failed to export spawn commands");
    SystemPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-system.ts"))
      .expect("Failed to export system commands");
    TranslationsPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-translations.ts"))
      .expect("Failed to export translations commands");
    // `visuals|read_geometry` is absent from this file by construction, and is generated beside it instead.
    VisualsPlugin::specta_builder::<R>()
      .export(command_exporter(), output.join("xrf-app-visuals.ts"))
      .expect("Failed to export visuals commands");
    export_raw_commands(
      &output.join("xrf-app-visuals-raw.ts"),
      crate::tauri_command_registry::visuals::NAME,
      crate::tauri_command_registry::visuals::RAW_COMMANDS,
      "xrf-app-visuals",
    );
  }
}
