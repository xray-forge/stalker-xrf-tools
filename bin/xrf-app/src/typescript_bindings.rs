const GENERATED_HEADER: &str = "// Auto-generated rust bindings. Do not edit it manually.\n";

const TAURI_SPECTA_HEADER: &str = "// This file has been generated by Tauri Specta. Do not edit this file manually.";

/// Marker Tauri Specta writes before the types it inlines into a command module.
///
/// Everything after it is a copy of a declaration owned by the crate the type comes from, so it is the cut
/// point where those copies are dropped in favour of imports.
const TYPES_MARKER: &str = "/* Types */";

/// Directory holding one module per crate that declares an exported type.
const TYPES_DIRECTORY: &str = "types";

/// Directory holding one module per Tauri plugin, each exporting only that plugin's commands.
const COMMANDS_DIRECTORY: &str = "commands";

/// Bindings import specifier root, matching the `@/*` path alias of the frontend.
const BINDINGS_ROOT: &str = "@/core/bindings";

/// Exports one plugin's commands while recording every type those commands referenced.
///
/// Tauri Specta inlines the full transitive closure of a plugin's command signatures and cannot reference a
/// declaration living in another file. Collecting the types here lets each one be written exactly once, into
/// the module of the crate that declares it, and the inlined copies replaced by imports afterwards.
struct CommandTypescript {
  exporter: Typescript,
  collected: Arc<Mutex<Types>>,
}

impl LanguageExt for CommandTypescript {
  type Error = specta_typescript::Error;

  fn export(self, config: &BuilderConfiguration, path: &Path) -> Result<(), Self::Error> {
    self
      .collected
      .lock()
      .expect("Collected types lock is poisoned")
      .extend(&config.types);

    LanguageExt::export(self.exporter, config, path)?;
    normalize_generated_bindings(path)?;

    Ok(())
  }
}

fn normalize_generated_bindings(path: &Path) -> io::Result<()> {
  let bindings = fs::read_to_string(path)?;

  fs::write(path, normalized(&bindings.replacen(TAURI_SPECTA_HEADER, "", 1)))
}

/// Generated source with Specta's doc comment indentation reduced to one space.
fn normalized(contents: &str) -> String {
  contents.replace("/**  ", "/** ").replace(" *  ", " * ")
}

#[derive(Debug, Clone)]
struct TypeScriptFormat {
  remapper: Remapper,
}

impl Default for TypeScriptFormat {
  fn default() -> Self {
    let number = <specta_typescript::Number as Type>::definition(&mut Types::default());
    let remapper = Remapper::new()
      .rule(DataType::Primitive(Primitive::usize), number.clone())
      .rule(DataType::Primitive(Primitive::isize), number.clone())
      .rule(DataType::Primitive(Primitive::u64), number.clone())
      .rule(DataType::Primitive(Primitive::i64), number.clone())
      .rule(DataType::Primitive(Primitive::u128), number.clone())
      .rule(DataType::Primitive(Primitive::i128), number.clone())
      .rule(
        <specta_typescript::BigInt as Type>::definition(&mut Types::default()),
        number,
      );

    Self { remapper }
  }
}

impl Format for TypeScriptFormat {
  fn map_types(&self, types: &Types) -> Result<Cow<'_, Types>, specta::FormatError> {
    let types = specta_serde::Format.map_types(types)?;

    Ok(Cow::Owned(self.remapper.remap_types(types.into_owned())))
  }

  fn map_type(&'_ self, types: &Types, data_type: &DataType) -> Result<Cow<'_, DataType>, specta::FormatError> {
    let data_type = specta_serde::Format.map_type(types, data_type)?;

    Ok(Cow::Owned(self.remapper.remap_dt(data_type.into_owned())))
  }
}

fn exporter() -> Typescript {
  let exporter: Exporter = Typescript::default().into();

  exporter.header(GENERATED_HEADER).framework_prelude("").into()
}

fn command_exporter(collected: Arc<Mutex<Types>>) -> CommandTypescript {
  CommandTypescript {
    exporter: exporter(),
    collected,
  }
}

/// The bindings module owning a type, taken from the crate that declares it.
///
/// `module_path!()` records the declaring crate as its first segment, so ownership is readable off every
/// collected type and nothing has to be listed by hand. A hand-written list is what previously let the crate
/// mirrors fall behind the command modules, duplicating a hundred declarations between them.
///
/// Answers `None` for a type no workspace crate declares, which has no module to live in.
fn owning_module(named: &NamedDataType) -> Option<String> {
  let declaring_crate: &str = named.module_path.split("::").next()?;

  declaring_crate
    .starts_with("xrf_")
    .then(|| declaring_crate.replace('_', "-"))
}

/// Where each collected type is declared, split by whether a workspace crate owns it.
struct TypeOwnership {
  /// Type name to the bindings module declaring it.
  owners: BTreeMap<String, String>,
  /// Type name to the foreign module path declaring it, for the ones no bindings module can hold.
  ///
  /// Tauri Specta registers `std::result::Result` whether or not the error handling mode makes use of it. One
  /// that stays unreferenced is simply absent from the output; one that is referenced has nowhere to live.
  foreign: BTreeMap<String, String>,
}

impl TypeOwnership {
  /// Fails when generated source names a type declared outside the workspace.
  fn assert_no_foreign_references(&self, source: &str, context: &str) {
    let referenced: BTreeSet<&str> = referenced_types(source, &self.foreign, "");

    assert!(
      referenced.is_empty(),
      "{context} references {referenced:?}, declared outside the workspace. Give them a module before use.",
    );
  }
}

/// Generated source with doc comments and string literals blanked out.
///
/// A type reference cannot be told from surrounding text by shape alone: class ids and pack modes render as
/// PascalCase string unions, and doc comment prose is capitalised. Removing both leaves only real code.
fn without_comments_and_strings(source: &str) -> String {
  let mut stripped: String = String::with_capacity(source.len());
  let mut characters = source.chars().peekable();

  while let Some(character) = characters.next() {
    match character {
      '/' if characters.peek() == Some(&'/') => {
        for skipped in characters.by_ref() {
          if skipped == '\n' {
            stripped.push('\n');
            break;
          }
        }
      }
      '/' if characters.peek() == Some(&'*') => {
        characters.next();

        let mut previous: char = '\0';

        for skipped in characters.by_ref() {
          if previous == '*' && skipped == '/' {
            break;
          }

          previous = skipped;
        }

        stripped.push(' ');
      }
      '"' | '\'' | '`' => {
        for skipped in characters.by_ref() {
          if skipped == character {
            break;
          }
        }

        stripped.push(' ');
      }
      _ => stripped.push(character),
    }
  }

  stripped
}

/// Names of generated types that `source` references and `owner` does not itself declare.
fn referenced_types<'a>(source: &str, owners: &'a BTreeMap<String, String>, owner: &str) -> BTreeSet<&'a str> {
  let source: String = without_comments_and_strings(source);
  let bytes: &[u8] = source.as_bytes();
  let mut referenced: BTreeSet<&str> = BTreeSet::new();
  let mut index: usize = 0;

  while index < bytes.len() {
    if !bytes[index].is_ascii_alphabetic() && bytes[index] != b'_' {
      index += 1;
      continue;
    }

    let start: usize = index;

    while index < bytes.len() && (bytes[index].is_ascii_alphanumeric() || bytes[index] == b'_') {
      index += 1;
    }

    // A property name is never a type reference; `Shape` renders its variants as `{ Sphere: .. }`.
    let trailing: &str = source[index..].trim_start();

    if trailing.starts_with(':') || trailing.starts_with("?:") {
      continue;
    }

    if let Some((name, module)) = owners.get_key_value(&source[start..index])
      && module != owner
    {
      referenced.insert(name.as_str());
    }
  }

  referenced
}

/// Import statements pulling every referenced type from the module that declares it.
fn render_imports(referenced: &BTreeSet<&str>, owners: &BTreeMap<String, String>) -> String {
  let mut grouped: BTreeMap<&str, Vec<&str>> = BTreeMap::new();

  for name in referenced {
    grouped
      .entry(
        owners
          .get(*name)
          .unwrap_or_else(|| panic!("`{name}` is referenced but has no owning module"))
          .as_str(),
      )
      .or_default()
      .push(name);
  }

  grouped
    .into_iter()
    .map(|(module, names)| {
      format!(
        "import {{ {} }} from \"{BINDINGS_ROOT}/{TYPES_DIRECTORY}/{module}\";\n",
        names.join(", ")
      )
    })
    .collect()
}

/// Fails when type modules would import each other.
///
/// Crate dependencies are acyclic, so a cycle here means ownership resolved wrongly rather than that the
/// sources are circular. TypeScript would not report it as an error, only as a partially initialised module.
fn assert_no_import_cycles(graph: &BTreeMap<String, BTreeSet<String>>) {
  fn walk(
    module: &str,
    graph: &BTreeMap<String, BTreeSet<String>>,
    path: &mut Vec<String>,
    settled: &mut BTreeSet<String>,
  ) {
    if settled.contains(module) {
      return;
    }

    assert!(
      !path.iter().any(|visited| visited == module),
      "Type modules import each other: {} -> {module}",
      path.join(" -> ")
    );

    path.push(module.to_string());

    for imported in graph.get(module).into_iter().flatten() {
      walk(imported, graph, path, settled);
    }

    path.pop();
    settled.insert(module.to_string());
  }

  let mut settled: BTreeSet<String> = BTreeSet::new();

  for module in graph.keys() {
    walk(module, graph, &mut Vec::new(), &mut settled);
  }
}

/// Writes one module per declaring crate and answers with the ownership those modules establish.
fn export_type_modules(output: &Path, collected: &Types) -> TypeOwnership {
  let types: Types = TypeScriptFormat::default()
    .map_types(collected)
    .expect("Failed to apply the TypeScript format to the collected types")
    .into_owned();
  let exporter: Exporter = exporter().into();

  let mut ownership: TypeOwnership = TypeOwnership {
    owners: BTreeMap::new(),
    foreign: BTreeMap::new(),
  };
  let mut modules: BTreeMap<String, Vec<&NamedDataType>> = BTreeMap::new();

  for named in types.into_sorted_iter() {
    if named.ty.is_none() {
      continue;
    }

    let Some(module) = owning_module(named) else {
      ownership
        .foreign
        .insert(named.name.to_string(), named.module_path.to_string());

      continue;
    };

    if let Some(previous) = ownership.owners.insert(named.name.to_string(), module.clone()) {
      assert_eq!(
        previous, module,
        "`{}` is declared by both `{previous}` and `{module}`",
        named.name
      );
    }

    modules.entry(module).or_default().push(named);
  }

  let mut graph: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
  let mut rendered: BTreeMap<String, String> = BTreeMap::new();

  for (module, named) in &modules {
    let declarations: String = primitives::export(&exporter, &types, named.iter().copied(), "")
      .unwrap_or_else(|error| panic!("Failed to export {module} types: {error}"));

    ownership.assert_no_foreign_references(&declarations, module);

    let referenced: BTreeSet<&str> = referenced_types(&declarations, &ownership.owners, module);

    graph.insert(
      module.clone(),
      referenced.iter().map(|name| ownership.owners[*name].clone()).collect(),
    );
    // `primitives::export` renders declarations alone, so the file header the high-level exporter would have
    // written has to be prepended here.
    let imports: String = render_imports(&referenced, &ownership.owners);
    let separator: &str = if imports.is_empty() { "" } else { "\n" };

    rendered.insert(
      module.clone(),
      format!("{GENERATED_HEADER}\n{imports}{separator}{declarations}"),
    );
  }

  assert_no_import_cycles(&graph);

  for (module, contents) in rendered {
    write_generated(&output.join(format!("{module}.ts")), &contents);
  }

  ownership
}

/// Replaces the types Tauri Specta inlined into a command module with imports, and names its commands.
///
/// The generated symbol was `commands` in every module, which left nine identical names in the directory and
/// made every call site alias it by hand.
fn finalize_command_module(path: &Path, plugin: &str, ownership: &TypeOwnership) {
  let contents: String =
    fs::read_to_string(path).unwrap_or_else(|error| panic!("Failed to read {}: {error}", path.display()));
  let commands: String = contents
    .split_once(TYPES_MARKER)
    .map_or(contents.as_str(), |(before, _)| before)
    .trim_end()
    .replace(
      "export const commands = {",
      &format!("export const {}Commands = {{", to_camel_case(plugin)),
    );

  ownership.assert_no_foreign_references(&commands, plugin);

  let referenced: BTreeSet<&str> = referenced_types(&commands, &ownership.owners, "");
  let (header, body) = commands
    .split_once("\n\n")
    .unwrap_or_else(|| panic!("{} has no header", path.display()));

  write_generated(
    path,
    &format!(
      "{header}\n\n{}{}\n",
      render_imports(&referenced, &ownership.owners),
      body.trim_start()
    ),
  );
}

/// Writes the wrappers for one domain's raw commands.
///
/// Specta cannot collect a command returning `tauri::ipc::Response`, so these are generated from the registry
/// instead of written by hand. The registry carries each argument's TypeScript type for exactly this reason;
/// the return is always `ArrayBuffer`, which is what the raw response arrives as.
fn export_raw_commands(path: &Path, plugin: &str, commands: &[(&str, &[(&str, &str)])], ownership: &TypeOwnership) {
  if commands.is_empty() {
    return;
  }

  let mut wrappers: String = String::new();

  for (wire_name, arguments) in commands {
    let parameters: String = arguments
      .iter()
      .map(|(name, argument_type)| format!("{name}: {argument_type}"))
      .collect::<Vec<String>>()
      .join(", ");
    let payload: String = arguments
      .iter()
      .map(|(name, _)| (*name).to_string())
      .collect::<Vec<String>>()
      .join(", ");

    wrappers.push_str(&format!(
      "  {}: ({parameters}): Promise<ArrayBuffer> =>\n    invokeRaw(\"plugin:{plugin}|{wire_name}\", {{ {payload} }}),\n",
      to_camel_case(wire_name)
    ));
  }

  ownership.assert_no_foreign_references(&wrappers, plugin);

  let referenced: BTreeSet<&str> = referenced_types(&wrappers, &ownership.owners, "");

  write_generated(
    path,
    &format!(
      "{GENERATED_HEADER}\nimport {{ invokeRaw }} from \"@/core/ipc/raw\";\n{}\n/** Commands answering with raw bytes, which Specta cannot type. */\nexport const {}RawCommands = {{\n{wrappers}}};\n",
      render_imports(&referenced, &ownership.owners),
      to_camel_case(plugin)
    ),
  );
}

fn write_generated(path: &Path, contents: &str) {
  fs::write(path, normalized(contents)).unwrap_or_else(|error| panic!("Failed to write {}: {error}", path.display()));
}

/// Empties a generated directory so the committed output is exactly what the current run produced.
fn reset_directory(path: &Path) {
  fs::create_dir_all(path).unwrap_or_else(|error| panic!("Failed to create {}: {error}", path.display()));

  for entry in fs::read_dir(path).unwrap_or_else(|error| panic!("Failed to read {}: {error}", path.display())) {
    let entry = entry.unwrap_or_else(|error| panic!("Failed to read an entry of {}: {error}", path.display()));

    if entry.path().extension().is_some_and(|extension| extension == "ts") {
      fs::remove_file(entry.path())
        .unwrap_or_else(|error| panic!("Failed to remove {}: {error}", entry.path().display()));
    }
  }
}

#[cfg(test)]
mod tests {
  use super::*;

  /// Every Tauri plugin whose commands are mirrored, as `(plugin name, Specta builder)`.
  fn command_modules<R: tauri::Runtime>() -> Vec<(&'static str, tauri_specta::Builder<R>)> {
    vec![
      (ArchivesPlugin::NAME, ArchivesPlugin::specta_builder::<R>()),
      (ConfigsPlugin::NAME, ConfigsPlugin::specta_builder::<R>()),
      (EquipmentIconsPlugin::NAME, EquipmentIconsPlugin::specta_builder::<R>()),
      (ExportsPlugin::NAME, ExportsPlugin::specta_builder::<R>()),
      (SpawnPlugin::NAME, SpawnPlugin::specta_builder::<R>()),
      (SystemPlugin::NAME, SystemPlugin::specta_builder::<R>()),
      (TranslationsPlugin::NAME, TranslationsPlugin::specta_builder::<R>()),
      // The raw `visuals` commands are absent from this builder by construction, and are generated beside it.
      (VisualsPlugin::NAME, VisualsPlugin::specta_builder::<R>()),
    ]
  }

  #[test]
  fn export_typescript_bindings() {
    let output: PathBuf = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../xrf-ui/src/core/bindings");
    let types_output: PathBuf = output.join(TYPES_DIRECTORY);
    let commands_output: PathBuf = output.join(COMMANDS_DIRECTORY);

    reset_directory(&types_output);
    reset_directory(&commands_output);

    let collected: Arc<Mutex<Types>> = Arc::new(Mutex::new(Types::default()));
    let plugins: Vec<(&str, tauri_specta::Builder<tauri::Wry>)> = command_modules();

    for (plugin, builder) in &plugins {
      builder
        .export(
          command_exporter(Arc::clone(&collected)),
          commands_output.join(format!("{plugin}.ts")),
        )
        .unwrap_or_else(|error| panic!("Failed to export {plugin} commands: {error}"));
    }

    let collected: Types = Arc::try_unwrap(collected)
      .unwrap_or_else(|_| panic!("Collected types are still borrowed"))
      .into_inner()
      .expect("Collected types lock is poisoned");
    let ownership: TypeOwnership = export_type_modules(&types_output, &collected);

    for (plugin, _) in &plugins {
      finalize_command_module(&commands_output.join(format!("{plugin}.ts")), plugin, &ownership);
    }

    export_raw_commands(
      &commands_output.join(format!("{}-raw.ts", crate::tauri_command_registry::visuals::NAME)),
      crate::tauri_command_registry::visuals::NAME,
      crate::tauri_command_registry::visuals::RAW_COMMANDS,
      &ownership,
    );
  }
}
